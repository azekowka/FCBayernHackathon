import { Sparkles } from 'lucide-react';
import { cn } from '@/lib/cn';

export type AiSourceLike = 'gemini' | 'demo' | 'fallback';

/**
 * Always tells the viewer which path produced a piece of text — live Gemini,
 * the offline demo template, or a guarded fallback after Gemini failed a check.
 */
export function AiBadge({
  source,
  model,
  latencyMs,
  note,
  className,
}: {
  source: AiSourceLike;
  model?: string | null;
  latencyMs?: number;
  note?: string;
  className?: string;
}) {
  const label =
    source === 'gemini'
      ? `Gemini${model ? ` · ${model}` : ''}`
      : source === 'demo'
        ? 'Demo AI · offline template'
        : 'Gemini → safe fallback';
  const title =
    source === 'fallback'
      ? `Gemini's answer failed a safety check (${note ?? 'unknown'}), so the grounded template was used.`
      : source === 'demo'
        ? 'No GEMINI_API_KEY configured — deterministic, grounded template.'
        : `Generated by ${model ?? 'Gemini'}${latencyMs ? ` in ${latencyMs} ms` : ''}; every number verified against the engine's facts.`;
  return (
    <span
      title={title}
      className={cn(
        'inline-flex items-center gap-1.5 rounded-full px-2.5 py-0.5 text-[11px] font-medium ring-1 ring-inset',
        source === 'gemini' && 'bg-u6/15 text-info ring-u6/40',
        source === 'demo' && 'bg-ink-700 text-fg-2 ring-line-strong',
        source === 'fallback' && 'bg-viz-amber/15 text-warn ring-viz-amber/40',
        className,
      )}
    >
      <Sparkles aria-hidden className="size-3" />
      {label}
      <span className="sr-only">. {title}</span>
    </span>
  );
}

export function TypingDots({ label = 'Thinking' }: { label?: string }) {
  return (
    <span role="status" className="inline-flex items-center gap-1" aria-label={label}>
      {[0, 1, 2].map((i) => (
        <span
          key={i}
          aria-hidden
          className="size-1.5 animate-blink rounded-full bg-fg-2"
          style={{ animationDelay: `${i * 0.18}s` }}
        />
      ))}
    </span>
  );
}
